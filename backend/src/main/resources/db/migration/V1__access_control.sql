CREATE TABLE app_users (
 id BIGSERIAL PRIMARY KEY,
 name VARCHAR(120) NOT NULL,
 email VARCHAR(255) NOT NULL UNIQUE,
 password_hash VARCHAR(255),
 enabled BOOLEAN NOT NULL DEFAULT TRUE,
 auth_version INTEGER NOT NULL DEFAULT 0,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE app_user_roles (
 user_id BIGINT NOT NULL REFERENCES app_users(id) ON DELETE CASCADE,
 role VARCHAR(20) NOT NULL CHECK(role IN ('ADMINISTRADOR','ORGANIZADOR','MARKETING')),
 PRIMARY KEY(user_id, role)
);
CREATE TABLE app_user_events (
 user_id BIGINT NOT NULL REFERENCES app_users(id) ON DELETE CASCADE,
 event_id BIGINT NOT NULL REFERENCES events(id) ON DELETE CASCADE,
 PRIMARY KEY(user_id,event_id)
);
CREATE TABLE app_activation_tokens (
 token_hash VARCHAR(64) PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES app_users(id) ON DELETE CASCADE,
 expires_at TIMESTAMPTZ NOT NULL,
 used_at TIMESTAMPTZ
);
CREATE TABLE event_public_access (
 event_id BIGINT PRIMARY KEY REFERENCES events(id) ON DELETE CASCADE,
 token VARCHAR(64) NOT NULL UNIQUE,
 enabled BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE TABLE app_access_audit (
 id BIGSERIAL PRIMARY KEY,
 actor_id BIGINT REFERENCES app_users(id),
 action VARCHAR(80) NOT NULL,
 target_id BIGINT,
 occurred_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
